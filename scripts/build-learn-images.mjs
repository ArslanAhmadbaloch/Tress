/**
 * Builds src/features/learn/article-photos.ts from the photo manifests.
 *
 *   node scripts/build-learn-images.mjs
 *
 * Each topic's photos live in assets/images/learn/<slug>.jpg with a
 * <topic>.credits.json manifest recording the Unsplash page, photographer
 * and licence. Metro needs static require() calls, so the map is
 * generated rather than built at runtime. Entries whose file is missing,
 * or whose slug no longer exists in the library, are skipped and listed.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PHOTOS = join(ROOT, 'assets', 'images', 'learn');
const OUT = join(ROOT, 'src', 'features', 'learn', 'article-photos.ts');

// Every slug the library knows, from the core file and the topic files.
const sources = [
  join(ROOT, 'src', 'features', 'learn', 'library.ts'),
  ...readdirSync(join(ROOT, 'src', 'features', 'learn', 'articles')).map((f) =>
    join(ROOT, 'src', 'features', 'learn', 'articles', f),
  ),
];
const known = new Set(
  sources.flatMap((f) => [...readFileSync(f, 'utf8').matchAll(/slug: '([^']+)'/g)].map((m) => m[1])),
);

const entries = [];
const skipped = [];
for (const manifest of readdirSync(PHOTOS).filter((f) => f.endsWith('.credits.json'))) {
  for (const e of JSON.parse(readFileSync(join(PHOTOS, manifest), 'utf8'))) {
    if (!existsSync(join(PHOTOS, e.file))) skipped.push(`${e.slug}: file missing`);
    else if (!known.has(e.slug)) skipped.push(`${e.slug}: not in library`);
    else entries.push(e);
  }
}
entries.sort((a, b) => a.slug.localeCompare(b.slug));

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const out = `/**
 * Article photographs and their credits.
 *
 * Generated by scripts/build-learn-images.mjs from the manifests in
 * assets/images/learn — do not edit by hand. Every photo is from Unsplash
 * under the Unsplash License, chosen to match its article's subject.
 */

export type PhotoCredit = { photographer: string; url: string };

export const ARTICLE_PHOTOS: Record<string, number> = {
${entries.map((e) => `  ${q(e.slug)}: require('@/assets/images/learn/${e.file}'),`).join('\n')}
};

export const ARTICLE_PHOTO_CREDITS: Record<string, PhotoCredit> = {
${entries.map((e) => `  ${q(e.slug)}: { photographer: ${q(e.photographer)}, url: ${q(e.photo)} },`).join('\n')}
};
`;
writeFileSync(OUT, out);
console.log(`${entries.length} photos mapped of ${known.size} articles.`);
if (skipped.length) console.log('Skipped:\n  ' + skipped.join('\n  '));
const missing = [...known].filter((s) => !entries.some((e) => e.slug === s));
if (missing.length) console.log(`Without a photo (${missing.length}): ${missing.join(', ')}`);
